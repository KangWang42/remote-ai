/* Generate Android's palette table from the page/terminal palette. --check is read-only. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = { window: {}, URL, document: { currentScript: { src: 'https://local.invalid/terminal/skins.js' } } };
vm.runInNewContext(fs.readFileSync(path.join(root, 'web/terminal/skins.js'), 'utf8'), context);
const skins = context.window.RemoteCliSkins;
// Keep Android's existing picker order and its light/default fallback indexes stable.
const names = ['night', 'slate', 'pine', 'dusk', 'paper', 'dawn', 'pond'];
if (names.length !== Object.keys(skins).length || names.some(name => !skins[name])) throw new Error('Update the Android theme order for the changed palette catalog');
const colors = names.map(name => {
  const s = skins[name];
  return [s.t.background, s.panel, s.raised, s.line, s.t.foreground, s.muted, s.accent, s.onAccent, s.t.green, s.t.yellow, s.t.red].map(color => {
    if (!/^#[a-f0-9]{6}$/i.test(color)) throw new Error('Invalid palette color: ' + name);
    return '0x' + color.slice(1);
  });
});
const text = `package io.github.kangwang42.remotecli;

// Generated by tools/sync_palettes.js from web/terminal/skins.js.
final class Palettes {
    static final int[][] COLORS = {
${colors.map(row => '        {' + row.join(', ') + '}').join(',\n')}
    };
    static final String[] NAMES = {${names.map(JSON.stringify).join(', ')}};
    static final String[] TITLES = {${names.map(name => JSON.stringify(skins[name].name + (skins[name].light ? ' · 明亮' : ''))).join(', ')}};
    private Palettes() {}
}
`;
const target = path.join(root, 'android/src/io/github/kangwang42/remotecli/Palettes.java');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== text) throw new Error('Android palettes differ; run node tools/sync_palettes.js');
  console.log('Android and embedded page palettes match (' + names.length + ' themes)');
} else fs.writeFileSync(target, text);
